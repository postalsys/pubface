// Builds the package.
//
// 1. Generates src/package-info.ts from package.json so that the library can
//    report its own name and version. It can not be a JSON import: those need
//    different syntax in ES modules and CommonJS.
// 2. Compiles src/ twice with tsc: once as ES modules into dist/esm and once as
//    CommonJS into dist/cjs. Each output directory gets its own package.json
//    that pins the module format.
//
// Every module keeps the exports tsc gives it: src/index.ts has named exports plus a default
// export object, so `require('pubface')` keeps returning an object with resolvePublicInterfaces.

import { spawnSync } from 'node:child_process';
import fs from 'node:fs';
import { createRequire } from 'node:module';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const require = createRequire(import.meta.url);
const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const tsc = require.resolve('typescript/bin/tsc');

function generatePackageInfo() {
    const pkg = JSON.parse(fs.readFileSync(path.join(root, 'package.json'), 'utf8'));
    const source =
        [
            '// Generated by scripts/build.js from package.json. Do not edit by hand.',
            '',
            `export const name = ${JSON.stringify(pkg.name)};`,
            `export const version = ${JSON.stringify(pkg.version)};`
        ].join('\n') + '\n';
    writeIfChanged(path.join(root, 'src', 'package-info.ts'), source);
}

// Skips the write when the content is already there so that tsc and tsx caches stay warm
function writeIfChanged(target, source) {
    if (!fs.existsSync(target) || fs.readFileSync(target, 'utf8') !== source) {
        fs.writeFileSync(target, source);
    }
}

function runTsc(project, ...args) {
    const result = spawnSync(process.execPath, [tsc, '-p', project, ...args], { cwd: root, stdio: 'inherit' });
    if (result.status !== 0) {
        process.exit(result.status || 1);
    }
}

function build() {
    generatePackageInfo();
    fs.rmSync(path.join(root, 'dist'), { recursive: true, force: true });

    runTsc('tsconfig.esm.json');
    // The ES module compile has already type-checked the same sources
    runTsc('tsconfig.cjs.json', '--noCheck');

    fs.writeFileSync(path.join(root, 'dist', 'esm', 'package.json'), JSON.stringify({ type: 'module' }, null, 4) + '\n');
    fs.writeFileSync(path.join(root, 'dist', 'cjs', 'package.json'), JSON.stringify({ type: 'commonjs' }, null, 4) + '\n');

    // npm marks bin files executable on install, a local checkout needs it for ./dist/cjs/cli.js
    fs.chmodSync(path.join(root, 'dist', 'cjs', 'cli.js'), 0o755);
}

if (process.argv.includes('--generate-only')) {
    generatePackageInfo();
} else {
    build();
}
